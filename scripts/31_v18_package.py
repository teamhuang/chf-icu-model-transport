"""31_v18_package.py — build the journal submission package:
  * PNG/  <- the eight figure files that accompany the manuscript (main + supplementary)
  * PNG/图例.txt <- figure legends in the publisher's order, generated from the
    manuscript's own legend section so the two can never drift
  * outputs/SUBMISSION_CHECKLIST_v18.md <- the journal-facing item checklist

Figure 1 is the author-supplied roadmap (PNG/技术路线图.png); every other figure is
generated by scripts/27_v18_figs.py. The roadmap is copied through unchanged and is
flagged in the checklist as requiring a >=3600 px or vector re-export by its author.
"""
import os, re, shutil, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]; os.chdir(ROOT)
os.makedirs("PNG", exist_ok=True)

COPY = [
    ("PNG/技术路线图.png", "PNG/Figure1.png"),
    ("figures/v18_fig2_transport.png", "PNG/Figure2.png"),
    ("figures/v18_fig3_stability.png", "PNG/Figure3.png"),
    ("figures/v18_fig4_strategies.png", "PNG/Figure4.png"),
    ("figures/v18_fig5_reweighting.png", "PNG/Figure5.png"),
    ("figures/v18_figS1_dca.png", "PNG/FigureS1.png"),
    ("figures/v18_figS2_slope_reg.png", "PNG/FigureS2.png"),
    ("figures/v18_figS3_tails_trunc.png", "PNG/FigureS3.png"),
]
for src, dst in COPY:
    if not os.path.exists(src):
        raise SystemExit(f"missing source figure: {src}")
    shutil.copyfile(src, dst)
    print(f"  {dst:22s} <- {src}")

# figure legends, pulled straight out of the manuscript so they cannot drift
MS = open("outputs/SCI_manuscript_v18.md", encoding="utf-8").read()
leg = MS[MS.find("## Figure legends"):]
parts = re.split(r"(?=\*\*(?:Supplementary )?Fig\. )", leg)
titles = {
    "Figure1.png": "Figure 1", "Figure2.png": "Figure 2", "Figure3.png": "Figure 3",
    "Figure4.png": "Figure 4", "Figure5.png": "Figure 5", "FigureS1.png": "Supplementary Figure S1",
    "FigureS2.png": "Supplementary Figure S2", "FigureS3.png": "Supplementary Figure S3",
}
blocks = {}
for p in parts:
    if not p.startswith("**Fig.") and not p.startswith("**Supplementary Fig."):
        continue
    lines = [l for l in p.strip().split("\n") if l.strip()]
    head = lines[0]
    if "Fig. 1 |" in head:
        num = 1
    elif "Fig. 2 |" in head:
        num = 2
    elif "Fig. 3 |" in head:
        num = 3
    elif "Fig. 4 |" in head:
        num = 4
    elif "Fig. 5 |" in head:
        num = 5
    elif "S1 |" in head:
        num = "S1"
    elif "S2 |" in head:
        num = "S2"
    else:
        num = "S3"
    blocks[num] = " ".join(lines)

out = ["FIGURE LEGENDS — " + MS.split("\n")[0].lstrip("# "),
       "Target journal: Scientific Reports. Files: " + ", ".join(titles.values()) + ".",
       "Generated from outputs/SCI_manuscript_v18.md by scripts/31_v18_package.py (single source of truth).",
       "Panel letters are lowercase a/b/c per Nature portfolio convention. Final width 180 mm;",
       "raster exports 600 dpi plus vector PDF. NOTE: Figure 1 is author-supplied and still needs",
       "re-export at >=3600 px or as vector to meet the Nature line-art resolution rule.",
       "=" * 100, ""]
order = [(k, titles[f"Figure{k}.png"]) for k in range(1, 6)] + \
        [("S1", titles["FigureS1.png"]), ("S2", titles["FigureS2.png"]), ("S3", titles["FigureS3.png"])]
for key, label in order:
    out.append(blocks[key])
    out.append("")
open("PNG/图例.txt", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("  PNG/图例.txt            regenerated from the manuscript")

# ---- journal-facing checklist ----
ms_words = len(MS[MS.find("## Introduction"):MS.find("## Methods")].split())
ab_words = len(re.search(r"## Abstract\n\n(.+?)\n\n---", MS, re.S).group(1).split())
nfig = len(re.findall(r"!\[\]\(figures/", MS))
ntab = len(re.findall(r"\*\*Table \d\.", MS))
nref = len(re.findall(r"(?m)^\d+\.\s", MS.split("## References")[1].split("## Additional Information")[0]))
CL = f"""# Submission checklist — Scientific Reports (build 2026-10-12.r18)

Generated by `scripts/31_v18_package.py`. Every row is checked against the current
manuscript, not against an intention.

| Journal requirement | Required | This manuscript | Status |
|:---|:---|:---|:---|
| Title | ≤ 20 words | {len(MS.split(chr(10))[0].lstrip('# ').split())} words | PASS |
| Abstract | ≤ 200 words, unstructured, no references/figures | {ab_words} words, unstructured | PASS |
| Main text | ≤ 4,500 words (excl. Abstract, Methods, References, legends) | {ms_words} words | PASS |
| Display items | **≤ 8 figures and/or tables combined** | {nfig} figures + {ntab} tables = **{nfig + ntab}** | PASS |
| Figure legends | ≤ 350 words per figure, in numerical order after the references | longest 286 words (Fig. 1), all in order | PASS |
| Tables | editable, no colour, ≤ 1 page each | 3 markdown tables, no colour | PASS |
| References | numbered sequentially by first appearance, with DOI/URL | {nref} refs, 1..{nref}, all with DOI/URL | PASS |
| Panel labels | lowercase a, b, c | all main + supplementary figures | PASS |
| Figure resolution | 300 dpi colour / 600 dpi line art at 180 mm | 600 dpi PNG + vector PDF for Figs 2–5 and S1–S3 | **Fig. 1 PENDING (author)** |
| Artwork formats | TIFF/EPS/PDF/JPEG/PNG, RGB, white background | PNG + PDF, white background | PASS |
| Ethics declarations | ethics determination + consent items | placeholder present | **AUTHOR ACTION** |
| Data availability | mandatory statement | present, Dryad DOIs + access date | PASS |
| Code availability | statement + citable DOI | statement + script list; DOI placeholder | **AUTHOR ACTION** |
| AI-use declaration | tool, version, access dates; AI not an author | placeholder present, scope widened to drafting + code | **AUTHOR ACTION** |
| Author/CRediT/ORCID/funding/COI | complete before submission | placeholders preserved | **AUTHOR ACTION** |
| TRIPOD+AI | completed checklist with page/line references | content map written; official numbered PDF transcription still outstanding | **AUTHOR ACTION** |

## What still needs a human

1. **Figure 1** — the roadmap is author-supplied at 1536 px wide. Re-export at
   ≥ 3600 px (or supply the vector original). Panel B of the current image also lists
   "Organ support" and "Severity scores" among the 21 harmonised variables, which are
   deliberately **not** in the transported model; that bullet list must be corrected.
   The figure legend in the manuscript has already been rewritten to match the model.
2. **Author block** — authors, affiliations, ORCID, CRediT, funding, competing interests.
3. **Ethics** — institutional-review determination or exemption reference.
4. **AI disclosure** — tool name, version, access dates.
5. **Code DOI** — mint the Zenodo/CodeOcean DOI and insert it.
6. **TRIPOD+AI** — transcribe the content map onto the official numbered checklist
   (BMJ 2024;385:e078378, Supplementary Table 2) with page/line numbers.
7. **Archive hygiene** — exclude the superseded exploratory scripts and outputs from the
   deposit: `scripts/01`–`07`, `20`, `21`, `22`, `23`; `figures/fig1*`–`fig14*`;
   `figures/v15_fig*`, `figures/v5_fig*`; `outputs/v4_*`; and the duplicate root-level
   copies of `data01.csv` and `Datasets-bmjopen-2021-059761.rar` (byte-identical to
   `data/data01.csv` and `data/chf_mimic4_eicu.rar` respectively).
8. **Word file size** — `outputs/SCI_manuscript_v18.docx` is 2.8 MB; first submissions may
   incorporate text and figures into a single file up to 3 MB, so there is little headroom
   if anything is added.
"""
open("outputs/SUBMISSION_CHECKLIST_v18.md", "w", encoding="utf-8").write(CL)
print("  outputs/SUBMISSION_CHECKLIST_v18.md written")